/**
 * Save visibility check results to JSON file (legacy single-page format)
 *
 * @returns Full path to the saved file
 */
export async function saveVisibilityCheckJson(
  url: string,
  allResults: Array<{check: BaseVisibilityCheck, result: VisibilityCheckResult}>,
  pageCaptured: PageCaptured,
  summary: {
    totalScore: number;
    totalMaxScore: number;
    percentage: number;
    grade: string;
  },
  todos: VisibilityTodoItem[] = [],
  location?: LocationData
): Promise<string> {
  try {
    // Build JSON structure
    const jsonOutput = buildVisibilityCheckJson(
      url,
      allResults,
      pageCaptured,
      summary,
      todos,
      location
    );

    // Get output directory for this website
    const outputDir = getUserProjectVisDir(url);

    // Ensure directory exists
    await mkdir(outputDir, { recursive: true });

    // Generate filename and full path
    const filename = generateFilename();
    const filepath = join(outputDir, filename);

    // Write JSON file with pretty formatting
    await writeFile(
      filepath,
      JSON.stringify(jsonOutput, null, 2),
      'utf-8'
    );

    logger.debug(`Visibility check results saved to: ${filepath}`);

    return filepath;
  } catch (error: any) {
    logger.error(`Failed to save visibility check JSON: ${error.message}`);
    throw error;
  }
}

/**
 * Save multi-page visibility check results to JSON and HTML files
 *
 * @returns Full path to the saved HTML report
 */
export async function saveMultiPageVisibilityCheckJson(
  rootUrl: string,
  serverResults: Array<{check: BaseVisibilityCheck, result: VisibilityCheckResult}>,
  pagesResults: Array<{
    url: string;
    path: string;
    results: Array<{check: BaseVisibilityCheck, result: VisibilityCheckResult}>;
    pageCaptured: PageCaptured;
  }>,
  totalSummary: {
    score: number;            // Normalized total score (0-100)
    scoreMax: number;         // Always 100
    percentage: number;
    grade: string;
    serverRawScore: number;
    serverRawMaxScore: number;
    pageNormalizedScores: number[];
    scoringFormula: string;
    numEntities: number;
  },
  todos: VisibilityTodoItem[] = [],
  location?: LocationData
): Promise<string> {
  try {
    // Build JSON structure
    const jsonOutput = buildMultiPageVisibilityCheckJson(
      rootUrl,
      serverResults,
      pagesResults,
      totalSummary,
      todos,
      location
    );

    // Get output directory for this website
    const outputDir = getUserProjectVisDir(rootUrl);

    // Ensure directory exists
    await mkdir(outputDir, { recursive: true });

    // Generate JSON filename and full path
    const filename = generateFilename();
    const filepath = join(outputDir, filename);
    const htmlFilepath = join(outputDir, 'index.html');

    // Write JSON file with pretty formatting
    await writeFile(
      filepath,
      JSON.stringify(jsonOutput, null, 2),
      'utf-8'
    );

    // Write a stable HTML entry point so users do not need to inspect JSON directly.
    await writeFile(
      htmlFilepath,
      renderVisibilityReportHtml(jsonOutput, filename),
      'utf-8'
    );

    logger.debug(`Multi-page visibility check JSON saved to: ${filepath}`);
    logger.debug(`Multi-page visibility check HTML saved to: ${htmlFilepath}`);

    return htmlFilepath;
  } catch (error: any) {
    logger.error(`Failed to save multi-page visibility check output: ${error.message}`);
    throw error;
  }
}
