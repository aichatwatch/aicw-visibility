/**
 * Generate a kebab-case ID from a check class name
 *
 * Examples:
 *   CheckServerRobotsTxt -> server-robots-txt
 *   CheckContentMetaTags -> content-meta-tags
 *   ServerBotAccessibilityFoundationModelsTraining -> server-bot-accessibility-foundation-models-training
 */
export function generateCheckId(checkClassName: string): string {
  // Remove "Check" prefix if present
  let id = checkClassName.replace(/^Check/, '');

  // Convert PascalCase to kebab-case
  id = id.replace(/([a-z])([A-Z])/g, '$1-$2');
  id = id.replace(/([A-Z])([A-Z][a-z])/g, '$1-$2');
  id = id.toLowerCase();

  return id;
}

/**
 * Get the category for a check based on its class name
 *
 * Categories: server, content, indexing, performance
 */
export function getCheckCategory(checkClassName: string): string {
  const lowerName = checkClassName.toLowerCase();

  if (lowerName.includes('server') || lowerName.includes('bot')) {
    return 'server';
  } else if (lowerName.includes('content')) {
    return 'content';
  } else if (lowerName.includes('indexing')) {
    return 'indexing';
  } else if (lowerName.includes('response') || lowerName.includes('speed')) {
    return 'performance';
  }

  return 'other';
}

/**
 * Extract performance data from PageCaptured object
 */
export function extractPerformanceData(pageCaptured?: PageCaptured): PerformanceData {
  if (!pageCaptured) {
    return {};
  }

  return {
    desktop_response_time_ms: pageCaptured.desktopResponseTimeMs,
    mobile_response_time_ms: pageCaptured.mobileResponseTimeMs,
    desktop_status_code: pageCaptured.desktopStatusCode,
    mobile_status_code: pageCaptured.mobileStatusCode,
    desktop_fetched_at: pageCaptured.desktopFetchedAt?.toISOString(),
    mobile_fetched_at: pageCaptured.mobileFetchedAt?.toISOString(),
  };
}

/**
 * Map a check result to JSON format
 * @param check - The visibility check instance
 * @param result - The check result
 * @param level - Whether this is a 'server' or 'page' level check (for group mapping)
 */
export function mapCheckResultToJson(
  check: BaseVisibilityCheck,
  result: VisibilityCheckResult,
  level: 'server' | 'page' = 'server'
): CheckResultJson {
  const checkClassName = check.constructor.name;
  const id = generateCheckId(checkClassName);
  const category = getCheckCategory(checkClassName);

  // Get hierarchical group info
  const groupInfo = getCheckGroupWithFallback(id, level);

  // Calculate percentage for this individual check (integer only)
  const score_percent = result.maxScore > 0
    ? Math.round((result.score / result.maxScore) * 100)
    : 0;

  // Extract sub_checks from metadata if present
  const sub_checks = result.metadata?.sub_checks as SubCheck[] | undefined;

  // Filter out sub_checks from metadata since it's now a top-level field
  const metadata = result.metadata ? { ...result.metadata } : undefined;
  if (metadata && 'sub_checks' in metadata) {
    delete metadata.sub_checks;
  }

  return {
    id,
    name: check.name,
    category,
    score: Math.round(result.score),  // Integer only
    score_max: result.maxScore,
    score_percent,
    passed: result.passed,
    message: result.details,
    error: result.error || false,
    metadata: Object.keys(metadata || {}).length > 0 ? metadata : undefined,
    sub_checks,
    // Hierarchical grouping
    parent_group: groupInfo.parentGroup,
    parent_group_tag: groupInfo.parentGroupTag,
    group: groupInfo.group,
    group_tag: groupInfo.groupTag,
  };
}

/**
 * Build grouped checks from a flat array of check results
 * Groups checks by their group_tag and calculates aggregate scores
 */
export function buildGroupedChecks(checks: CheckResultJson[]): Record<string, CheckGroupResult> {
  const groups: Record<string, CheckGroupResult> = {};

  for (const check of checks) {
    const groupTag = check.group_tag;

    if (!groups[groupTag]) {
      groups[groupTag] = {
        group: check.group,
        group_tag: groupTag,
        checks: [],
        score: 0,
        max_score: 0,
        score_percent: 0,
      };
    }

    groups[groupTag].checks.push(check);
    groups[groupTag].score += check.score;
    groups[groupTag].max_score += check.score_max;
  }

  // Calculate percentages and sort checks within each group
  for (const group of Object.values(groups)) {
    group.score_percent = group.max_score > 0
      ? Math.round((group.score / group.max_score) * 100)
      : 0;
    // Sort checks by their name for consistent display
    group.checks.sort((a, b) => a.name.localeCompare(b.name));
  }

  // Return groups sorted by display order
  const sortedGroups: Record<string, CheckGroupResult> = {};
  const sortedKeys = Object.keys(groups).sort((a, b) =>
    getGroupOrder(a) - getGroupOrder(b)
  );
  for (const key of sortedKeys) {
    sortedGroups[key] = groups[key];
  }

  return sortedGroups;
}

/**
 * Determine priority based on check ID and score impact
 * Used by todo generator
 */
export function determinePriority(
  result: VisibilityCheckResult,
  checkId: string
): VisibilityTodoItem['priority'] {
  // Critical priority for key visibility blockers
  const criticalChecks = ['server-robots-txt', 'server-bot-accessibility'];
  if (criticalChecks.some(c => checkId.includes(c)) && result.score === 0) {
    return 'critical';
  }

  // High priority for significant score impact
  const scoreLoss = result.maxScore - result.score;
  if (scoreLoss >= 10) {
    return 'high';
  }

  // Medium priority for moderate impact
  if (scoreLoss >= 5) {
    return 'medium';
  }

  return 'low';
}

/**
 * Calculate estimated impact score (potential points gained if fixed)
 */
export function calculateImpactScore(result: VisibilityCheckResult): number {
  // Impact is the potential points that could be gained
  const potentialGain = result.maxScore - result.score;
  // Cap at 20 per the interface spec
  return Math.min(Math.round(potentialGain), 20);
}

/**
 * Determine product category based on check type or product name
 */
function getProductCategory(productName: string, checkId?: string): AIServiceResult['product_category'] {
  const lowerName = productName.toLowerCase();

  // Check for specific patterns
  if (lowerName.includes('search') || lowerName.includes('bing') || lowerName.includes('brave')) {
    return 'search';
  }
  if (lowerName.includes('chatgpt') || lowerName.includes('claude') || lowerName.includes('gemini') || lowerName.includes('perplexity') || lowerName.includes('grok')) {
    return 'assistant';
  }
  if (lowerName.includes('training') || lowerName.includes('llama') || lowerName.includes('foundation')) {
    return 'training';
  }
  if (lowerName.includes('scholar') || lowerName.includes('research')) {
    return 'research';
  }

  return 'general';
}

/**
 * Extract AI services from bot accessibility check results
 * Aggregates ai_services_summary from metadata into top-level array
 */
export function extractAIServices(
  allResults: Array<{check: BaseVisibilityCheck, result: VisibilityCheckResult}>
): AIServiceResult[] {
  // Map to aggregate services by name (to avoid duplicates across multiple bot checks)
  const serviceMap = new Map<string, AIServiceResult>();

  for (const {check, result} of allResults) {
    const checkId = generateCheckId(check.constructor.name);

    // Check for ai_services_summary in metadata
    const aiServicesSummary = result.metadata?.ai_services_summary as Array<{
      service_name: string;
      service_url?: string;
      accessible: boolean;
      bots_tested: string[];
      bots_accessible_count: number;
      bots_total_count: number;
      score_contribution: number;
    }> | undefined;

    if (!aiServicesSummary) continue;

    // Also get detailed bot results if available
    const botResults = result.metadata?.results as Array<{
      bot: string;
      accessible: boolean;
      status: number;
      size: number;
    }> | undefined;

    for (const summary of aiServicesSummary) {
      const existing = serviceMap.get(summary.service_name);

      // Get bots for this service from the detailed results
      const bots: BotResult[] = [];
      if (botResults) {
        for (const botName of summary.bots_tested) {
          const botResult = botResults.find(r => r.bot === botName);
          if (botResult) {
            bots.push({
              bot_name: botResult.bot,
              accessible: botResult.accessible,
              status_code: botResult.status,
              response_size: botResult.size,
            });
          }
        }
      }

      if (existing) {
        // Merge: service is accessible if accessible in ANY check
        existing.accessible = existing.accessible || summary.accessible;
        existing.score += summary.score_contribution;
        existing.bots.push(...bots);
      } else {
        serviceMap.set(summary.service_name, {
          product_name: summary.service_name,
          product_url: summary.service_url || '',
          product_category: getProductCategory(summary.service_name, checkId),
          accessible: summary.accessible,
          score: summary.score_contribution,
          score_max: summary.score_contribution, // Will be adjusted
          bots,
        });
      }
    }
  }

  // Sort by product name for consistent output
  return Array.from(serviceMap.values()).sort((a, b) =>
    a.product_name.localeCompare(b.product_name)
  );
}

/**
 * Build complete visibility check JSON structure
 *
 * @param url - URL that was checked
 * @param allResults - Array of check results
 * @param pageCaptured - Page capture data
 * @param summary - Score summary
 * @param todos - Todo items generated by todo-generator.ts
 * @param location - Optional location data
 */
export function buildVisibilityCheckJson(
  url: string,
  allResults: Array<{check: BaseVisibilityCheck, result: VisibilityCheckResult}>,
  pageCaptured: PageCaptured,
  summary: {
    totalScore: number;
    totalMaxScore: number;
    percentage: number;
    grade: string;
  },
  todos: VisibilityTodoItem[] = [],
  location?: LocationData
): VisibilityCheckJsonOutput {
  // Use provided location or default
  const locationData = location || {
    country_code: DEFAULT_CHECK_LOCATION.COUNTRY_CODE,
    country_name: DEFAULT_CHECK_LOCATION.COUNTRY_NAME,
    geo_id: DEFAULT_CHECK_LOCATION.GEO_ID,
    geo_name: DEFAULT_CHECK_LOCATION.GEO_NAME,
  };

  // Extract performance data once (at root level, not duplicated in checks)
  const performance = extractPerformanceData(pageCaptured);

  // Map all check results to JSON format (without performance duplication)
  const checks = allResults.map(({check, result}) =>
    mapCheckResultToJson(check, result)
  );

  return {
    created_at: new Date().toISOString(),
    author: AICW_VISIBILITY_AUTHOR,
    url,
    normalized_name: normalizeWebsiteName(url),
    location: locationData,
    performance,  // Performance data at root level
    score: Math.round(summary.totalScore),  // Integer only
    score_max: summary.totalMaxScore,
    score_percent: summary.percentage,
    grade: summary.grade,
    checks,
    todos,  // Todos passed from caller (generated by todo-generator.ts)
  };
}

/**
 * Build multi-page visibility check JSON structure with normalized scoring
 *
 * @param rootUrl - Root domain URL
 * @param serverResults - Array of server-level check results
 * @param pagesResults - Array of page-level results with their checks
 * @param totalSummary - Normalized scoring summary with formula
 * @param todos - Todo items generated by todo-generator.ts
 * @param location - Optional location data
 */
export function buildMultiPageVisibilityCheckJson(
  rootUrl: string,
  serverResults: Array<{check: BaseVisibilityCheck, result: VisibilityCheckResult}>,
  pagesResults: Array<{
    url: string;
    path: string;
    results: Array<{check: BaseVisibilityCheck, result: VisibilityCheckResult}>;
    pageCaptured: PageCaptured;
  }>,
  totalSummary: {
    score: number;            // Normalized total score (0-100)
    scoreMax: number;         // Always 100
    percentage: number;
    grade: string;
    serverRawScore: number;
    serverRawMaxScore: number;
    pageNormalizedScores: number[];
    scoringFormula: string;
    numEntities: number;
  },
  todos: VisibilityTodoItem[] = [],
  location?: LocationData
): MultiPageVisibilityCheckJsonOutput {
  // Use provided location or default
  const locationData = location || {
    country_code: DEFAULT_CHECK_LOCATION.COUNTRY_CODE,
    country_name: DEFAULT_CHECK_LOCATION.COUNTRY_NAME,
    geo_id: DEFAULT_CHECK_LOCATION.GEO_ID,
    geo_name: DEFAULT_CHECK_LOCATION.GEO_NAME,
  };

  // Build server results with normalized scoring
  const serverChecks = serverResults.map(({check, result}) =>
    mapCheckResultToJson(check, result, 'server')
  );

  // Build grouped server checks for hierarchical UI
  const serverGroups = buildGroupedChecks(serverChecks);

  // Calculate server normalized score (0-100)
  const serverNormalizedScore = totalSummary.serverRawMaxScore > 0
    ? (totalSummary.serverRawScore / totalSummary.serverRawMaxScore) * 100
    : 0;

  const server: ServerResults = {
    score: Math.round(serverNormalizedScore),
    score_max: 100,
    score_percent: Math.round(serverNormalizedScore),
    raw_score: totalSummary.serverRawScore,
    raw_max_score: totalSummary.serverRawMaxScore,
    checks: serverChecks,
    groups: serverGroups
  };

  // Build pages results with normalized scoring
  const pages: PageResults[] = pagesResults.map(({url, path, results, pageCaptured}, idx) => {
    const pageChecks = results.map(({check, result}) =>
      mapCheckResultToJson(check, result, 'page')
    );

    // Build grouped page checks for hierarchical UI
    const pageGroups = buildGroupedChecks(pageChecks);

    // Calculate raw scores for this page
    const pageRawScore = results.reduce((sum, {result}) =>
      result.error ? sum : sum + result.score, 0
    );
    const pageRawMaxScore = results.reduce((sum, {result}) =>
      sum + result.maxScore, 0
    );

    // Get the pre-calculated normalized score for this page
    const pageNormalizedScore = totalSummary.pageNormalizedScores[idx] ?? 0;

    return {
      url,
      path,
      score: Math.round(pageNormalizedScore),
      score_max: 100,
      score_percent: Math.round(pageNormalizedScore),
      raw_score: Math.round(pageRawScore),
      raw_max_score: pageRawMaxScore,
      performance: extractPerformanceData(pageCaptured),
      checks: pageChecks,
      groups: pageGroups
    };
  });

  // Combine all results for AI services extraction
  const allResults = [...serverResults, ...pagesResults.flatMap(p => p.results)];
  const ai_services = extractAIServices(allResults);

  return {
    created_at: new Date().toISOString(),
    author: AICW_VISIBILITY_AUTHOR,
    url: rootUrl,
    normalized_name: normalizeWebsiteName(rootUrl),
    location: locationData,
    score: totalSummary.score,
    score_max: 100,
    score_percent: totalSummary.percentage,
    grade: totalSummary.grade,
    server,
    pages,
    scoring_summary: {
      num_entities: totalSummary.numEntities,
      formula: totalSummary.scoringFormula,
    },
    ai_services,
    todos,  // Todos passed from caller (generated by todo-generator.ts)
  };
}

/**
 * Generate filename for visibility check JSON output
 * Format: YYYY-MM-DD-{timestamp}-data.json
 */
export function generateFilename(): string {
  const now = new Date();
  const date = now.toISOString().split('T')[0];  // YYYY-MM-DD
  const timestamp = now.getTime();
  return `${date}-${timestamp}-data.json`;
}

function escapeHtml(value: unknown): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function scoreClass(score: number): string {
  if (score >= 80) return 'good';
  if (score >= 60) return 'warn';
  return 'bad';
}

function statusClass(check: CheckResultJson): string {
  if (check.error) return 'bad';
  if (!check.passed) return 'warn';
  return 'good';
}

function renderChecks(checks: CheckResultJson[]): string {
  return checks.map(check => {
    const status = check.error ? 'Fail' : check.passed ? 'Pass' : 'Warn';
    const score = check.error ? 'ERR' : `${check.score}/${check.score_max}`;
    return `
      <tr>
        <td><span class="pill ${statusClass(check)}">${status}</span></td>
        <td>
          <strong>${escapeHtml(check.name)}</strong>
          <div class="muted">${escapeHtml(check.group)}</div>
        </td>
        <td>${escapeHtml(score)}</td>
        <td>${escapeHtml(check.message)}</td>
      </tr>
    `;
  }).join('');
}

function renderTodos(todos: VisibilityTodoItem[]): string {
  if (!todos.length) {
    return '<p class="muted">No todo items generated.</p>';
  }

  return todos.map(todo => `
    <article class="todo">
      <div>
        <span class="pill ${todo.priority === 'critical' || todo.priority === 'high' ? 'bad' : todo.priority === 'medium' ? 'warn' : 'good'}">${escapeHtml(todo.priority)}</span>
        <strong>${escapeHtml(todo.title)}</strong>
      </div>
      <p>${escapeHtml(todo.description)}</p>
      ${todo.steps.length ? `<ol>${todo.steps.map(step => `<li>${step.text}</li>`).join('')}</ol>` : ''}
    </article>
  `).join('');
}

function renderAiServices(services: AIServiceResult[]): string {
  if (!services.length) {
    return '<p class="muted">No AI service data available.</p>';
  }

  return services.map(service => `
    <tr>
      <td>${service.product_url ? `<a href="${escapeHtml(service.product_url)}">${escapeHtml(service.product_name)}</a>` : escapeHtml(service.product_name)}</td>
      <td><span class="pill ${service.accessible ? 'good' : 'bad'}">${service.accessible ? 'Accessible' : 'Blocked'}</span></td>
      <td>${escapeHtml(service.product_category)}</td>
      <td>${escapeHtml(service.bots.length)}</td>
    </tr>
  `).join('');
}

