/**
 * Todo item generated from visibility checks
 *
 * Replaces the old Issue and Recommendation types with a unified,
 * actionable format that can be tracked and completed by users.
 */
export interface VisibilityTodoItem {
  /** Stable, unique action identifier for deduplication (e.g., "server-robots-txt-allow-chatgpt") */
  action_id: string;

  /** Related check ID (e.g., "server-robots-txt") */
  check_id: string;

  /** Short, actionable title (e.g., "Allow GPTBot in robots.txt") */
  title: string;

  /** Detailed description of what to do and why */
  description: string;

  /** Recurrence period in days: -1 = one-time, 7 = weekly, 30 = monthly, 90 = quarterly */
  period_days: number;

  /** Priority level affecting sort order */
  priority: 'critical' | 'high' | 'medium' | 'low';

  /** Estimated score improvement if completed (0-20) */
  impact_score: number;

  /** Checkable steps with HTML content and completion state */
  steps: TodoStep[];

  /** Optional code example */
  code_example?: string;

  /** Optional documentation URL */
  documentation_url?: string;

  /** Category for grouping (derived from check_id) */
  category: 'server' | 'content' | 'indexing' | 'performance';

  /** Source tag for filtering */
  tag: TodoTag;

  /** Optional: Page URL for page-specific todos */
  page_url?: string;

  /** Hierarchical parent group: "server" for server-level, "pages" for page-level (added by todo generator) */
  parent_group?: 'server' | 'pages';

  /** Hierarchical subgroup: "config", "ai_access", "content", etc. (added by todo generator) */
  group?: string;
}

